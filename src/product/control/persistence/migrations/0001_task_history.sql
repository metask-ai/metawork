-- Product-owned history structure. Runtime bootstrap and recovery are separate.
-- Fixed-width unsigned identities and arbitrary UTF-8 strings bind as BLOB.

CREATE TABLE history_state (
    singleton INTEGER NOT NULL CHECK(typeof(singleton)='integer' AND singleton=1),
    default_permission_profile TEXT NOT NULL CHECK(typeof(default_permission_profile)='text' AND default_permission_profile IN ('approval_required','full_access')),
    next_workspace_id BLOB NOT NULL CHECK(typeof(next_workspace_id)='blob' AND length(next_workspace_id)=8 AND next_workspace_id<>X'0000000000000000'),
    next_workspace_recent_order BLOB NOT NULL CHECK(typeof(next_workspace_recent_order)='blob' AND length(next_workspace_recent_order)=8 AND next_workspace_recent_order<>X'0000000000000000'),
    next_task_id BLOB NOT NULL CHECK(typeof(next_task_id)='blob' AND length(next_task_id)=8 AND next_task_id<>X'0000000000000000'),
    next_task_recent_order BLOB NOT NULL CHECK(typeof(next_task_recent_order)='blob' AND length(next_task_recent_order)=8 AND next_task_recent_order<>X'0000000000000000'),
    PRIMARY KEY(singleton)
);
CREATE TABLE history_failures (
    ordinal INTEGER NOT NULL CHECK(typeof(ordinal)='integer' AND ordinal>=0 AND ordinal<=4294967295),
    task_id BLOB NOT NULL CHECK(typeof(task_id)='blob' AND length(task_id)=8 AND task_id<>X'0000000000000000'),
    recent_order BLOB NOT NULL CHECK(typeof(recent_order)='blob' AND length(recent_order)=8 AND recent_order<>X'0000000000000000'),
    reason BLOB NOT NULL CHECK(typeof(reason)='blob' AND length(reason)>0),
    PRIMARY KEY(ordinal)
);
CREATE TABLE workspaces (
    id BLOB NOT NULL CHECK(typeof(id)='blob' AND length(id)=8 AND id<>X'0000000000000000'),
    epoch BLOB NOT NULL CHECK(typeof(epoch)='blob' AND length(epoch)=8 AND epoch<>X'0000000000000000'),
    kind TEXT NOT NULL CHECK(typeof(kind)='text' AND kind IN ('manual','automatic')),
    canonical_root BLOB NOT NULL CHECK(typeof(canonical_root)='blob' AND length(canonical_root)>0),
    display_name BLOB NOT NULL CHECK(typeof(display_name)='blob' AND length(display_name)>0),
    visible INTEGER NOT NULL CHECK(typeof(visible)='integer' AND visible IN (0,1)),
    recent_order BLOB NOT NULL CHECK(typeof(recent_order)='blob' AND length(recent_order)=8),
    PRIMARY KEY(id),
    UNIQUE(canonical_root)
);
CREATE TABLE tasks (
    id BLOB NOT NULL CHECK(typeof(id)='blob' AND length(id)=8 AND id<>X'0000000000000000'),
    recent_order BLOB NOT NULL CHECK(typeof(recent_order)='blob' AND length(recent_order)=8 AND recent_order<>X'0000000000000000'),
    completion_seen_run_id BLOB CHECK(completion_seen_run_id IS NULL OR (typeof(completion_seen_run_id)='blob' AND length(completion_seen_run_id)=8)),
    workspace_id BLOB NOT NULL CHECK(typeof(workspace_id)='blob' AND length(workspace_id)=8 AND workspace_id<>X'0000000000000000'),
    workspace_epoch BLOB NOT NULL CHECK(typeof(workspace_epoch)='blob' AND length(workspace_epoch)=8 AND workspace_epoch<>X'0000000000000000'),
    workspace_root BLOB NOT NULL CHECK(typeof(workspace_root)='blob' AND length(workspace_root)>0),
    title BLOB NOT NULL CHECK(typeof(title)='blob'),
    title_redacted INTEGER NOT NULL CHECK(typeof(title_redacted)='integer' AND title_redacted IN (0,1)),
    archived INTEGER NOT NULL CHECK(typeof(archived)='integer' AND archived IN (0,1)),
    permission_profile TEXT NOT NULL CHECK(typeof(permission_profile)='text' AND permission_profile IN ('approval_required','full_access')),
    permission_interaction TEXT NOT NULL CHECK(typeof(permission_interaction)='text' AND permission_interaction IN ('interactive','noninteractive')),
    binding_epoch BLOB NOT NULL CHECK(typeof(binding_epoch)='blob' AND length(binding_epoch)=8 AND binding_epoch<>X'0000000000000000'),
    execution_generation BLOB NOT NULL CHECK(typeof(execution_generation)='blob' AND length(execution_generation)=8 AND execution_generation<>X'0000000000000000'),
    protocol TEXT NOT NULL CHECK(typeof(protocol)='text' AND protocol IN ('openai_responses','anthropic_messages','openai_chat_completions','gemini_native')),
    model BLOB NOT NULL CHECK(typeof(model)='blob' AND length(model)>0),
    next_run_generation BLOB NOT NULL CHECK(typeof(next_run_generation)='blob' AND length(next_run_generation)=8),
    active_operation_kind TEXT CHECK(active_operation_kind IS NULL OR (typeof(active_operation_kind)='text' AND active_operation_kind IN ('run','compact'))),
    active_operation_id BLOB CHECK(active_operation_id IS NULL OR (typeof(active_operation_id)='blob' AND length(active_operation_id)=8 AND active_operation_id<>X'0000000000000000')),
    checkpoint_anchor TEXT NOT NULL CHECK(typeof(checkpoint_anchor)='text'),
    checkpoint_attempt TEXT NOT NULL CHECK(typeof(checkpoint_attempt)='text'),
    PRIMARY KEY(id),
    FOREIGN KEY(workspace_id) REFERENCES workspaces(id),
    CHECK((active_operation_kind IS NULL AND active_operation_id IS NULL) OR (active_operation_kind IS NOT NULL AND active_operation_id IS NOT NULL))
);
CREATE TABLE runs (
    task_id BLOB NOT NULL CHECK(typeof(task_id)='blob' AND length(task_id)=8 AND task_id<>X'0000000000000000'),
    id BLOB NOT NULL CHECK(typeof(id)='blob' AND length(id)=8 AND id<>X'0000000000000000'),
    ordinal INTEGER NOT NULL CHECK(typeof(ordinal)='integer' AND ordinal>=0 AND ordinal<=4294967295),
    generation BLOB NOT NULL CHECK(typeof(generation)='blob' AND length(generation)=8 AND generation<>X'0000000000000000'),
    execution_generation BLOB NOT NULL CHECK(typeof(execution_generation)='blob' AND length(execution_generation)=8 AND execution_generation<>X'0000000000000000'),
    execution_protocol TEXT NOT NULL CHECK(typeof(execution_protocol)='text' AND execution_protocol IN ('openai_responses','anthropic_messages','openai_chat_completions','gemini_native')),
    execution_model BLOB NOT NULL CHECK(typeof(execution_model)='blob' AND length(execution_model)>0),
    permission_profile TEXT NOT NULL CHECK(typeof(permission_profile)='text' AND permission_profile IN ('approval_required','full_access')),
    permission_interaction TEXT NOT NULL CHECK(typeof(permission_interaction)='text' AND permission_interaction IN ('interactive','noninteractive')),
    input_json TEXT NOT NULL CHECK(typeof(input_json)='text'),
    assistant BLOB NOT NULL CHECK(typeof(assistant)='blob'),
    assistant_redacted INTEGER NOT NULL CHECK(typeof(assistant_redacted)='integer' AND assistant_redacted IN (0,1)),
    commentary_ends_json TEXT NOT NULL CHECK(typeof(commentary_ends_json)='text'),
    assistant_output_kind TEXT CHECK(assistant_output_kind IS NULL OR (typeof(assistant_output_kind)='text' AND assistant_output_kind IN ('final','partial'))),
    assistant_output_start BLOB CHECK(assistant_output_start IS NULL OR (typeof(assistant_output_start)='blob' AND length(assistant_output_start)=8)),
    submitted_at_unix_ms INTEGER CHECK(submitted_at_unix_ms IS NULL OR (typeof(submitted_at_unix_ms)='integer' AND submitted_at_unix_ms>0)),
    finished_at_unix_ms INTEGER CHECK(finished_at_unix_ms IS NULL OR (typeof(finished_at_unix_ms)='integer' AND finished_at_unix_ms>0)),
    phase TEXT NOT NULL CHECK(typeof(phase)='text' AND phase IN ('queued','running','waiting_ui','stopping','completed','stopped','cancelled','interrupted','failed')),
    outcome TEXT CHECK(outcome IS NULL OR (typeof(outcome)='text')),
    cause TEXT CHECK(cause IS NULL OR (typeof(cause)='text')),
    input_tokens BLOB NOT NULL CHECK(typeof(input_tokens)='blob' AND length(input_tokens)=8),
    output_tokens BLOB NOT NULL CHECK(typeof(output_tokens)='blob' AND length(output_tokens)=8),
    cache_read_input_tokens BLOB NOT NULL CHECK(typeof(cache_read_input_tokens)='blob' AND length(cache_read_input_tokens)=8),
    cache_creation_input_tokens BLOB NOT NULL CHECK(typeof(cache_creation_input_tokens)='blob' AND length(cache_creation_input_tokens)=8),
    file_change_observation TEXT CHECK(file_change_observation IS NULL OR (typeof(file_change_observation)='text' AND file_change_observation IN ('collecting','complete','incomplete'))),
    diagnostic BLOB NOT NULL CHECK(typeof(diagnostic)='blob'),
    diagnostic_truncated INTEGER NOT NULL CHECK(typeof(diagnostic_truncated)='integer' AND diagnostic_truncated IN (0,1)),
    diagnostic_redacted INTEGER NOT NULL CHECK(typeof(diagnostic_redacted)='integer' AND diagnostic_redacted IN (0,1)),
    event_projection_failure TEXT CHECK(event_projection_failure IS NULL OR (typeof(event_projection_failure)='text' AND event_projection_failure IN ('consumer_rejected','dependency_contract_failure'))),
    next_activity_order BLOB NOT NULL CHECK(typeof(next_activity_order)='blob' AND length(next_activity_order)=8 AND next_activity_order<>X'0000000000000000'),
    PRIMARY KEY(task_id,id),
    UNIQUE(task_id,generation),
    UNIQUE(task_id,ordinal),
    FOREIGN KEY(task_id) REFERENCES tasks(id),
    CHECK((assistant_output_kind IS NULL AND assistant_output_start IS NULL) OR (assistant_output_kind IS NOT NULL AND assistant_output_start IS NOT NULL))
);
CREATE TABLE run_tools (
    task_id BLOB NOT NULL CHECK(typeof(task_id)='blob' AND length(task_id)=8 AND task_id<>X'0000000000000000'),
    run_id BLOB NOT NULL CHECK(typeof(run_id)='blob' AND length(run_id)=8 AND run_id<>X'0000000000000000'),
    id BLOB NOT NULL CHECK(typeof(id)='blob' AND length(id)>0),
    ordinal INTEGER NOT NULL CHECK(typeof(ordinal)='integer' AND ordinal>=0 AND ordinal<=4294967295),
    activity_order BLOB NOT NULL CHECK(typeof(activity_order)='blob' AND length(activity_order)=8 AND activity_order<>X'0000000000000000'),
    name BLOB NOT NULL CHECK(typeof(name)='blob' AND length(name)>0),
    input BLOB NOT NULL CHECK(typeof(input)='blob'),
    progress BLOB NOT NULL CHECK(typeof(progress)='blob'),
    content BLOB NOT NULL CHECK(typeof(content)='blob'),
    state TEXT NOT NULL CHECK(typeof(state)='text' AND state IN ('running','completed','failed')),
    is_error INTEGER NOT NULL CHECK(typeof(is_error)='integer' AND is_error IN (0,1)),
    elapsed_ms BLOB NOT NULL CHECK(typeof(elapsed_ms)='blob' AND length(elapsed_ms)=8),
    input_truncated INTEGER NOT NULL CHECK(typeof(input_truncated)='integer' AND input_truncated IN (0,1)),
    progress_truncated INTEGER NOT NULL CHECK(typeof(progress_truncated)='integer' AND progress_truncated IN (0,1)),
    content_truncated INTEGER NOT NULL CHECK(typeof(content_truncated)='integer' AND content_truncated IN (0,1)),
    redacted INTEGER NOT NULL CHECK(typeof(redacted)='integer' AND redacted IN (0,1)),
    file_refs_json TEXT CHECK(file_refs_json IS NULL OR (typeof(file_refs_json)='text')),
    PRIMARY KEY(task_id,run_id,id),
    UNIQUE(task_id,run_id,ordinal),
    UNIQUE(task_id,run_id,activity_order),
    FOREIGN KEY(task_id,run_id) REFERENCES runs(task_id,id),
    CHECK((state='failed')=is_error)
);
CREATE TABLE run_file_changes (
    task_id BLOB NOT NULL CHECK(typeof(task_id)='blob' AND length(task_id)=8 AND task_id<>X'0000000000000000'),
    run_id BLOB NOT NULL CHECK(typeof(run_id)='blob' AND length(run_id)=8 AND run_id<>X'0000000000000000'),
    id BLOB NOT NULL CHECK(typeof(id)='blob' AND length(id)>0),
    ordinal INTEGER NOT NULL CHECK(typeof(ordinal)='integer' AND ordinal>=0 AND ordinal<=4294967295),
    activity_order BLOB NOT NULL CHECK(typeof(activity_order)='blob' AND length(activity_order)=8 AND activity_order<>X'0000000000000000'),
    kind TEXT NOT NULL CHECK(typeof(kind)='text' AND kind IN ('created','modified','deleted','moved')),
    status TEXT NOT NULL CHECK(typeof(status)='text' AND status IN ('applied','partial')),
    display_path BLOB NOT NULL CHECK(typeof(display_path)='blob' AND length(display_path)>0),
    from_display_path BLOB CHECK(from_display_path IS NULL OR (typeof(from_display_path)='blob' AND length(from_display_path)>0)),
    before_bytes BLOB NOT NULL CHECK(typeof(before_bytes)='blob' AND length(before_bytes)=8),
    after_bytes BLOB NOT NULL CHECK(typeof(after_bytes)='blob' AND length(after_bytes)=8),
    artifact_run_generation BLOB CHECK(artifact_run_generation IS NULL OR (typeof(artifact_run_generation)='blob' AND length(artifact_run_generation)=8 AND artifact_run_generation<>X'0000000000000000')),
    artifact_change_order BLOB CHECK(artifact_change_order IS NULL OR (typeof(artifact_change_order)='blob' AND length(artifact_change_order)=8 AND artifact_change_order<>X'0000000000000000')),
    artifact_digest BLOB CHECK(artifact_digest IS NULL OR (typeof(artifact_digest)='blob' AND length(artifact_digest)=32)),
    artifact_byte_size BLOB CHECK(artifact_byte_size IS NULL OR (typeof(artifact_byte_size)='blob' AND length(artifact_byte_size)=8 AND artifact_byte_size<>X'0000000000000000')),
    diff_complete INTEGER NOT NULL CHECK(typeof(diff_complete)='integer' AND diff_complete IN (0,1)),
    redacted INTEGER NOT NULL CHECK(typeof(redacted)='integer' AND redacted IN (0,1)),
    PRIMARY KEY(task_id,run_id,id),
    UNIQUE(task_id,run_id,ordinal),
    UNIQUE(task_id,run_id,activity_order),
    FOREIGN KEY(task_id,run_id) REFERENCES runs(task_id,id),
    CHECK((artifact_run_generation IS NULL AND artifact_change_order IS NULL AND artifact_digest IS NULL AND artifact_byte_size IS NULL) OR (artifact_run_generation IS NOT NULL AND artifact_change_order IS NOT NULL AND artifact_digest IS NOT NULL AND artifact_byte_size IS NOT NULL)),
    CHECK((kind='moved')=(from_display_path IS NOT NULL))
);
