import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const input = new URL(
  "../build_support/unicode/CaseFolding-17.0.0.txt",
  import.meta.url,
);
const output = new URL(
  "../src/product/task/search_casefold_data.zig",
  import.meta.url,
);
const digest =
  "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183";

// This is an offline transformation of one pinned Unicode data file. It does
// not fetch dependencies or infer case rules from the generator's host locale.
export async function generateSearchCasefold({ check = false } = {}) {
  const bytes = await readFile(input);
  assert.equal(createHash("sha256").update(bytes).digest("hex"), digest);
  const mappings = [];
  for (const line of bytes.toString("utf8").split(/\r?\n/)) {
    const fields = line
      .split("#")[0]
      .split(";")
      .map((part) => part.trim());
    if (!["C", "F"].includes(fields[1])) continue;
    mappings.push({
      point: Number.parseInt(fields[0], 16),
      folded: fields[2].split(" ").map((value) => Number.parseInt(value, 16)),
    });
  }
  const rows = [];
  for (let index = 0; index < mappings.length; index++) {
    const first = mappings[index];
    assert.ok(first.folded.length >= 1 && first.folded.length <= 3);
    let end = index;
    const step = mappings[index + 1]?.point - first.point;
    if (first.folded.length === 1 && (step === 1 || step === 2))
      while (
        mappings[end + 1]?.folded.length === 1 &&
        mappings[end + 1].point - mappings[end].point === step &&
        mappings[end + 1].folded[0] - mappings[end + 1].point ===
          first.folded[0] - first.point
      )
        end++;
    rows.push([
      first.point,
      mappings[end].point,
      end === index ? 1 : step,
      ...Array.from({ length: 3 }, (_, offset) => first.folded[offset] ?? 0),
    ]);
    index = end;
  }
  // Check the compact representation independently against every source entry.
  for (const { point, folded } of mappings) {
    const row = rows.find(([first, last]) => first <= point && point <= last);
    assert.ok(row && (point - row[0]) % row[2] === 0);
    const actual = row.slice(3).filter(Boolean);
    actual[0] += point - row[0];
    assert.deepEqual(actual, folded);
  }
  const source =
    "// Generated by scripts/generate-search-casefold.mjs; do not edit.\n" +
    "// Source: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt\n" +
    `// SHA-256: ${digest}\n` +
    "// Copyright Unicode, Inc.; license: frontend/public/licenses/UNICODE.txt\n" +
    "// Rows: first codepoint, last, stride, then up to three folded codepoints.\n" +
    "// Zero padding is not part of the mapping; unlisted codepoints are unchanged.\n" +
    "pub const mappings = [_][6]u21{\n" +
    rows
      .map(
        (row) =>
          `    .{ ${row.map((value) => `0x${value.toString(16)}`).join(", ")} },`,
      )
      .join("\n") +
    "\n};\n";
  if (check)
    assert.equal(
      await readFile(output, "utf8"),
      source,
      "Regenerate the search casefold data",
    );
  else await writeFile(output, source);
  return { entries: mappings.length, ranges: rows.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  console.log(
    await generateSearchCasefold({ check: process.argv.includes("--check") }),
  );
